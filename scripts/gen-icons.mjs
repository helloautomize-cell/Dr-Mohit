// Generates components/icons.tsx from resources/images/icons/*.svg
// Duotone icons (viewBox 48, class .di) -> Icon; line icons (viewBox 24) -> LIcon.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'resources/images/icons';
const files = readdirSync(DIR).filter((f) => f.endsWith('.svg'));

const toJsx = (s) =>
  s
    .replace(/stroke-width=/g, 'strokeWidth=')
    .replace(/stroke-linecap=/g, 'strokeLinecap=')
    .replace(/stroke-linejoin=/g, 'strokeLinejoin=')
    .replace(/clip-rule=/g, 'clipRule=')
    .replace(/fill-rule=/g, 'fillRule=')
    .replace(/stroke-dasharray=/g, 'strokeDasharray=')
    .replace(/stroke-miterlimit=/g, 'strokeMiterlimit=')
    .replace(/class="b"/g, 'className="b"')
    // make themable: pale bg circle -> .b (CSS fills it with --t), brand stroke -> currentColor
    .replace(/fill="#EEF3FB"/g, 'className="b"')
    .replace(/stroke="#1D4E9E"/g, 'stroke="currentColor"')
    .replace(/fill="none" /g, 'fill="none" ');

const duotone = {};
const line = {};
for (const f of files) {
  const name = f.replace(/^(duotone|line)-/, '').replace(/\.svg$/, '');
  const raw = readFileSync(join(DIR, f), 'utf8');
  const inner = raw.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  (f.startsWith('duotone-') ? duotone : line)[name] = toJsx(inner.trim());
}

const out = `// AUTO-GENERATED by scripts/gen-icons.mjs - do not edit by hand.
// Sources: resources/images/icons/*.svg (duotone = 48px, line = 24px).
import type { JSX } from 'react';

export type IconName = ${Object.keys(duotone).map((k) => JSON.stringify(k)).join(' | ') || 'never'};
export type LineIconName = ${Object.keys(line).map((k) => JSON.stringify(k)).join(' | ') || 'never'};

const D: Record<IconName, JSX.Element> = {
${Object.entries(duotone)
  .map(([k, v]) => `  ${JSON.stringify(k)}: <>${v}</>,`)
  .join('\n')}
};

const L: Record<LineIconName, JSX.Element> = {
${Object.entries(line)
  .map(([k, v]) => `  ${JSON.stringify(k)}: <>${v}</>,`)
  .join('\n')}
};

export function Icon({ name, className }: { name: IconName; className?: string }) {
  return (
    <svg viewBox="0 0 48 48" className={\`di \${className ?? ''}\`} aria-hidden="true">
      {D[name]}
    </svg>
  );
}

export function LIcon({ name, className }: { name: LineIconName; className?: string }) {
  return (
    <svg viewBox="0 0 24 24" className={className} fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      {L[name]}
    </svg>
  );
}
`;
writeFileSync('components/icons.tsx', out);
console.log(`wrote components/icons.tsx: ${Object.keys(duotone).length} duotone, ${Object.keys(line).length} line icons`);
